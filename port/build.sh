signing_success=0
for signing_attempt in 1 2 3; do
    # File Provider can restore FinderInfo on the app directory while building.
    /usr/bin/xattr -cr "$app_dir"
    if /usr/bin/codesign --force --sign - --digest-algorithm=sha1,sha256 --timestamp=none "$app_dir"; then signing_success=1; break; fi
done
if [ "$signing_success" != 1 ]; then
    # File Provider can restore attributes faster than codesign reads them.
    # Sign and package a clean local snapshot outside its managed directory.
    signing_stage=$(mktemp -d /private/tmp/osu-sign.XXXXXX)
    trap 'rm -rf "$signing_stage"' EXIT
    /usr/bin/ditto --norsrc --noextattr "$app_dir" "$signing_stage/OsuLegacy.app"
    app_dir="$signing_stage/OsuLegacy.app"
    /usr/bin/codesign --force --sign - --digest-algorithm=sha1,sha256 --timestamp=none "$app_dir"
fi
python3 "$root_dir/probes/sign-legacy.py" "$app_dir/OsuLegacy"
/usr/bin/codesign --verify "$app_dir"
file "$app_dir/OsuLegacy"
python3 "$port_dir/package.py" "$app_dir" "$out_dir/OsuLegacy-armv6-ios421-experimental.ipa"
version=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleVersion' "$app_dir/Info.plist")
snapshot="$out_dir/version-$version"
mkdir -p "$snapshot"
cp "$app_dir/OsuLegacy" "$snapshot/OsuLegacy"
cp "$out_dir/OsuLegacy-armv6-ios421-experimental.ipa" "$snapshot/OsuLegacy.ipa"
dsymutil "$app_dir/OsuLegacy" -o "$snapshot/OsuLegacy.dSYM"
echo "Experimental app built: $out_dir/OsuLegacy-armv6-ios421-experimental.ipa (not device-tested)"
