"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/GpuRenderer.m" -o "$out_dir/GpuRenderer.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/DebugMetrics.m" -o "$out_dir/DebugMetrics.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/Video.m" -o "$out_dir/Video.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/Artwork.c" -o "$out_dir/Artwork.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/Sound.m" -o "$out_dir/Sound.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/Startup.m" -o "$out_dir/Startup.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/MenuTriangles.m" -o "$out_dir/MenuTriangles.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/MenuVisuals.m" -o "$out_dir/MenuVisuals.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/MenuSpectrum.c" -o "$out_dir/MenuSpectrum.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/MenuAudioPCM.m" -o "$out_dir/MenuAudioPCM.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -I"$ffmpeg/include" -c "$port_dir/Native/AudioDecode.c" -o "$out_dir/AudioDecode.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -I"$ffmpeg/include" -c "$port_dir/Native/AudioRate.c" -o "$out_dir/AudioRate.o"
"$root_dir/toolchain/armv6-clang" -g -O2 -c "$port_dir/Native/AudioCache.m" -o "$out_dir/AudioCache.o"
