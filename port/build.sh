cp "$port_dir/ThirdParty/playlist-provenance.md" "$app_dir/Licences/"
cp "$port_dir/ThirdParty/menu-effects-provenance.md" "$app_dir/Licences/"
cp "$port_dir/ThirdParty/gameplay-provenance.md" "$app_dir/Licences/"
cp "$port_dir/ThirdParty/results-provenance.md" "$app_dir/Licences/"
cp "$port_dir/ThirdParty/catch-provenance.md" "$app_dir/Licences/"
cp "$port_dir/ThirdParty/taiko-conversion-provenance.md" "$app_dir/Licences/"
