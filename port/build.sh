MONO_PATH="$app_dir/managed:$out_dir" mono "$out_dir/ModTests.exe"
mcs -nostdlib -r:"$corlib" -r:"$app_dir/managed/OsuLegacy.Core.dll" -r:"$out_dir/UiTests.exe" -out:"$out_dir/BeatmapEditorTests.exe" "$port_dir/Tests/BeatmapEditorTests.cs"
MONO_PATH="$app_dir/managed:$out_dir" mono "$out_dir/BeatmapEditorTests.exe"
mcs -nostdlib -r:"$corlib" -r:"$app_dir/managed/OsuLegacy.Core.dll" -r:"$out_dir/UiTests.exe" -out:"$out_dir/OnlineBrowserTests.exe" "$port_dir/Tests/OnlineBrowserTests.cs"
