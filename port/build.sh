mcs -nostdlib -r:"$corlib" -r:"$app_dir/managed/OsuLegacy.Core.dll" -out:"$out_dir/UiTests.exe" "$port_dir/Managed/MenuPlaylist.cs" "$port_dir/Managed/MusicPlayerUi.cs" "$port_dir/Managed/LocalScores.cs" "$port_dir/Managed/LazerUi.cs" "$port_dir/Managed/HudDrawing.cs" "$port_dir/Managed/HudEditorUi.cs" "$port_dir/Managed/BeatmapEditorUi.cs" "$port_dir/Managed/OnlineBrowserUi.cs" "$port_dir/Managed/GameplayView.cs" "$port_dir/Managed/ResultsScreen.cs" "$port_dir/Tests/UiTests.cs" "$port_dir/Tests/ArtworkTests.cs"
MONO_PATH="$app_dir/managed" mono "$out_dir/UiTests.exe" "$port_dir/Assets" "$root_dir/build/ui-preview"
mcs -nostdlib -r:"$corlib" -r:"$app_dir/managed/OsuLegacy.Core.dll" -r:"$out_dir/UiTests.exe" -out:"$out_dir/ResultsTests.exe" "$port_dir/Tests/ResultsTests.cs"
MONO_PATH="$app_dir/managed:$out_dir" mono "$out_dir/ResultsTests.exe" "$port_dir/Assets" "$root_dir/build/ui-preview"
mcs -nostdlib -r:"$corlib" -r:"$app_dir/managed/OsuLegacy.Core.dll" -r:"$out_dir/UiTests.exe" -out:"$out_dir/CatchTests.exe" "$port_dir/Tests/CatchTests.cs"
MONO_PATH="$app_dir/managed:$out_dir" mono "$out_dir/CatchTests.exe" "$port_dir/Assets" "$root_dir/build/ui-preview"
