    "$out_dir/Artwork.o" "$out_dir/Sound.o" "$out_dir/Startup.o" "$out_dir/MenuTriangles.o" "$out_dir/MenuVisuals.o" "$out_dir/MenuSpectrum.o" "$out_dir/MenuAudioPCM.o" "$out_dir/AudioDecode.o" "$out_dir/AudioRate.o" "$out_dir/AudioCache.o" "$out_dir/OszImport.o" "$out_dir/unzip.o" "$out_dir/ioapi.o" \
    "$out_dir/MirrorHttp.o" "$root_dir/build/bearssl/armv6/libbearssl.a" "$out_dir/AppleAudio.o" "$out_dir/SongList.o" "$out_dir/ImportGate.o" "$ffmpeg/lib/libavfilter.a" "$ffmpeg/lib/libavformat.a" "$ffmpeg/lib/libavcodec.a" "$ffmpeg/lib/libswresample.a" "$ffmpeg/lib/libavutil.a" \
    "$mono_build/mono/mini/.libs/libmini-static.a" \
    "$mono_build/mono/metadata/.libs/libmonoruntimesgen-static.a" \
    "$mono_build/mono/io-layer/.libs/libwapi.a" \
    "$mono_build/mono/utils/.libs/libmonoutils.a" \
    "$mono_build/eglib/src/.libs/libeglib.a" \
